import { beforeEach, afterAll, it, expect, vi } from 'vitest';
import { render, screen, fireEvent, waitFor, act } from '@testing-library/react';
import { createRequire } from 'node:module';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
const bridge=vi.hoisted(()=>({state:{currentProject:null},api:vi.fn()}));
vi.mock('../../lib/legacy.js',()=>({legacy:bridge}));
import WritingStyleWorkbench, { writingStyleHandoff } from './WritingStyleWorkbench.jsx';
process.env.FILM_DATA_DIR=fs.mkdtempSync(path.join(os.tmpdir(),'fe-style-ui-'));
const require=createRequire(import.meta.url);
const {db}=require('../../../backend/db/database.js');
require('../../../backend/db/schema.js').ensureSchema();
const {handleWritingStyle}=require('../../../backend/routes/writing-style.js');
beforeEach(()=>{
 const id=crypto.randomUUID();db.prepare('INSERT INTO film_projects(id,title) VALUES (?,?)').run(id,'My writing project');
 bridge.state.currentProject={id,title:'My writing project'};
 bridge.api.mockImplementation(async(url,options={})=>{
  let status,raw;
  handleWritingStyle({method:options.method||'GET',body:options.body?JSON.parse(options.body):{}},{writeHead(s){status=s;},end(s){raw=s;}},['film',...url.split('/').filter(Boolean)]);
  const result=JSON.parse(raw);if(status>=400)throw Error(result.error);return result;
 });
 vi.spyOn(window,'confirm').mockReturnValue(true);
});
afterAll(()=>db.close());
it('real UI-to-API handoff captures authorship, proposes inactive profile, approves and saves feedback',async()=>{
 render(<WritingStyleWorkbench />);act(()=>{window.dispatchEvent(new Event('film:open-my-voice'));});
 await screen.findByText('No approved profile. Your style is inactive.');
 expect(screen.getByText('Save draft profile').disabled).toBe(true);
 fireEvent.change(screen.getByLabelText('Writing sample'),{target:{value:'I watched the rain find its way down the window. The room stayed quiet.'}});
 fireEvent.change(screen.getByLabelText('Source and provenance'),{target:{value:'Original unaided journal note'}});
 fireEvent.change(screen.getByLabelText('Authorship'),{target:{value:'original_human'}});
 fireEvent.click(screen.getByLabelText(/I confirm these are my original words/));
 fireEvent.click(screen.getByText('Save evidence'));
 const sample=await screen.findByLabelText(/Original unaided journal note · original_human · confirmed/);
 fireEvent.click(sample);
 fireEvent.change(screen.getByLabelText('Proposed style guidance'),{target:{value:'Plain words. Concrete observations. Let silence stand.'}});
 fireEvent.click(screen.getByText('Save draft profile'));
 await screen.findByText('Version 1 · draft');
 expect(screen.getByText('No approved profile. Your style is inactive.')).toBeTruthy();
 fireEvent.click(screen.getByLabelText('I reviewed this Film profile, its direct preferences and any original sample evidence.'));fireEvent.click(screen.getByText('Approve reviewed profile'));
 await screen.findByText('Active approved profile: version 1');
 fireEvent.change(screen.getByLabelText('What sounds like you, and what does not?'),{target:{value:'Keep it less polished.'}});
 fireEvent.click(screen.getByText('Save feedback'));
 await screen.findByText('Version 1: Keep it less polished.');
 const state=await bridge.api(`/projects/${bridge.state.currentProject.id}/writing-style`);
 expect(state.active_profile.sample_ids).toEqual([state.samples[0].id]);
 expect(state.samples[0].authorship).toBe('original_human');
 expect(db.prepare('SELECT count(*) n FROM film_scripts WHERE project_id=?').get(bridge.state.currentProject.id).n).toBe(0);
});
it('AI-edited imports remain labelled, cannot be confirmed or selected for voice evidence',async()=>{
 render(<WritingStyleWorkbench />);act(()=>{window.dispatchEvent(new Event('film:open-my-voice'));});
 await screen.findByText('No approved profile. Your style is inactive.');
 fireEvent.change(screen.getByLabelText('Writing sample'),{target:{value:'A scene that was heavily edited by an AI assistant.'}});
 fireEvent.change(screen.getByLabelText('Source and provenance'),{target:{value:'AI screenplay rewrite'}});
 fireEvent.change(screen.getByLabelText('Authorship'),{target:{value:'ai_assisted'}});
 expect(screen.getByLabelText(/I confirm these/).disabled).toBe(true);
 fireEvent.click(screen.getByText('Save evidence'));
 const sample=await screen.findByLabelText(/AI screenplay rewrite · ai_assisted · not style evidence/);
 expect(sample.disabled).toBe(true);
 expect(screen.getByText('Save draft profile').disabled).toBe(true);
});
it('portable JSON import is passed to the real API without automatic approval',async()=>{
 render(<WritingStyleWorkbench />);act(()=>{window.dispatchEvent(new Event('film:open-my-voice'));});
 await screen.findByText('No approved profile. Your style is inactive.');
 const empty={schema_version:'1.0.0',profile_name:'Private writing profile',profile_version:'0.0.0',owner:'Manny',status:'empty',sources:[],approved_rules:[],approved_examples:[],pending_proposals:[],feedback:[],history:[],prior_snapshots:[],apply_instruction:'Use only approved rules.'};
 const file={name:'profile.json',size:500,text:async()=>JSON.stringify(empty)};
 fireEvent.change(screen.getByLabelText('Profile JSON file'),{target:{files:[file]}});
 await screen.findByText('Private writing profile · 0.0.0');
 fireEvent.click(screen.getByText('Preview import and conflicts'));
 await screen.findByLabelText('Import review');
 fireEvent.click(screen.getByText('Import profile for local review'));
 await waitFor(()=>expect(bridge.api).toHaveBeenCalledWith(expect.stringContaining('/import'),expect.objectContaining({method:'POST'})));
 const result=await bridge.api(`/projects/${bridge.state.currentProject.id}/writing-style/export`);
 expect(result.status).toBe('empty');expect(result.prior_snapshots[0].profile.profile_name).toBe('Private writing profile');
});
