#!/usr/bin/env node
/*
 * Builds src/index.html: a TEST-ONLY reassembly of this app as one page, so the
 * backend's UI tests (which read src/index.html, as they do in film-engine) run
 * against the port's own files. Never served; gitignored; rebuilt by npm test.
 *
 * Everything comes from what this app ships: the markup files, the two
 * stylesheets, and the code in public/legacy (core, chunks, production-graph,
 * shell, vendor). Code is laid out in the source's statement order, one
 * <script data-legacy="…"> per run of statements from the same file, so a test
 * that compiles each script alone sees which file broke, and a test that scans
 * "the next function after X" sees the source's order.
 */
const fs = require('fs');
const path = require('path');
const { parse, readSource, topLevelElements, innerOf, replacedStatement } = require('./split-lib');

const ROOT = path.join(__dirname, '..');
const plan = require('./port-plan.json');
const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
const stripHeader = (code) => code.replace(/^\/\* GENERATED by tools\/split-map\.js[^\n]*\*\/\n/, '');

function assemble() {
    const src = readSource(path.join(ROOT, plan.source));
    const map = JSON.parse(read('docs/split-map.json'));

    // ── Code, in source order, from the port's files ────────────────────
    const files = ['public/legacy/core.js', ...Object.keys(map.chunks).map(c => `public/legacy/chunks/${c}.js`)];
    const pool = new Map(); // statement text -> [file, …]
    const navInPort = {};
    for (const f of files) {
        const code = stripHeader(read(f));
        for (const n of parse(code).body) {
            const t = code.slice(n.start, n.end);
            if (n.type === 'FunctionDeclaration' && n.id.name === 'navigateTo') { navInPort.file = f; navInPort.text = t; continue; }
            if (t === `var ${map.core.loaderPlaceholders.join(', ')};`) { navInPort.placeholders = t; continue; } // the port's one added statement
            pool.set(t, [...(pool.get(t) || []), f]);
        }
    }
    const runs = [];
    const appAst = parse(src.app);
    // What a React page replaced (functions, its own constants) is in no port file, by design (src/pages/<id>/react.json).
    const replaced = new Set(Object.values(map.react || {}).flatMap(r => r.replaces));
    let prev = 0;
    for (const n of appAst.body) {
        if (replacedStatement(n, replaced)) { prev = n.end; continue; }
        const lead = src.app.slice(prev, n.start); // comments and blank lines before it, as in the source
        prev = n.end;
        const t = src.app.slice(n.start, n.end);
        let file, text = t;
        if (n.type === 'FunctionDeclaration' && n.id.name === 'navigateTo') ({ file, text } = { file: navInPort.file, text: (navInPort.placeholders ? navInPort.placeholders + '\n\n    ' : '') + navInPort.text });
        else {
            const at = pool.get(t);
            if (!at || !at.length) throw new Error('a source statement is in no port file: ' + t.slice(0, 80));
            file = at.shift();
        }
        const last = runs[runs.length - 1];
        if (last && last.file === file) last.code += lead + text;
        else runs.push({ file, code: lead + text });
    }
    const left = [...pool.values()].flat();
    if (left.length) throw new Error(`${left.length} port statements matched no source statement`);

    // ── Markup, in the source's body order ──────────────────────────────
    const registry = read('src/pages/registry.js');
    const pageIds = [...registry.matchAll(/\{ id: '([a-z0-9]+)'/g)].map(m => m[1]);
    const modalsIdx = read('src/components/modals/index.js');
    const modals = [...modalsIdx.matchAll(/\{ id: '([^']+)', html: m\d+, inMain: (true|false) \}/g)].map(m => ({ id: m[1], inMain: m[2] === 'true' }));
    const html = (f) => read(f).replace(/\n$/, '');
    // A React page's markup is what it renders before any data arrives, rendered here to static HTML,
    // so the UI tests that read controls (ids, data-field, labels) see the real React page.
    /*
     * A React page has no markup.html, so the comments that preceded it in the source (which a legacy
     * page's markup.html keeps) would vanish, and some backend tests bound a section by them
     * (setup-models reads the Settings page up to "CODEX:START ops-compliance-pages", which sits before
     * Job Queue). They are taken from the pinned source itself: the same lead the split gives markup files.
     */
    const leadOf = (() => {
        const mainEl = topLevelElements(src.html).find(e => e.cls === 'main');
        const inner = innerOf(mainEl.outer);
        const kids = topLevelElements(inner);
        const out = {};
        kids.forEach((e, i) => {
            if (!(e.id || '').startsWith('page-')) return;
            const lead = inner.slice(i ? kids[i - 1].end : 0, e.start);
            out[e.id.slice(5)] = /<!--/.test(lead) ? lead.replace(/^\s*\n/, '').replace(/\s+$/, '') + '\n' : '';
        });
        return out;
    })();
    const pageHtml = (id) => map.react && map.react[id] ? (leadOf[id] || '') + renderReactPage(id) : html(`src/pages/${id}/markup.html`);
    const main = '<div class="main">\n' + pageIds.map(pageHtml).join('\n')
        + modals.filter(m => m.inMain).map(m => '\n' + html(`src/components/modals/${m.id}.html`)).join('') + '\n</div>';
    const body = [html('src/components/Sidebar/sidebar.html'), main, html('src/components/StatusBar/status-bar.html'),
        ...modals.filter(m => !m.inMain).map(m => html(`src/components/modals/${m.id}.html`))].join('\n');

    /*
     * The React pages' own source, as inert text. Many backend UI tests read the page's SOURCE (does a
     * paid control go through confirmPaidImage, is there an uploadControl('marketing-asset'…)); for a
     * React page that source is its .jsx, not a <script>. A <template> is never run by a browser and is
     * not a <script>, so the checks that compile every script block do not see it; the checks that read
     * source text do. The static render above is what the page DRAWS; this is what it RUNS.
     */
    const reactSource = Object.keys(map.react || {}).sort().map(id => {
        const dir = path.join(ROOT, 'src/pages', id);
        const files = fs.readdirSync(dir).filter(f => f.endsWith('.jsx') && !f.includes('.test.') && f !== 'index.jsx').sort();
        // Import lines dropped: they are wiring, not behaviour, and the page's no-bundler check reads them as ES modules in the page.
        const text = files.map(f => read(`src/pages/${id}/${f}`)).join('\n').replace(/^import\b[^\n]*$/gm, '// (import omitted in the test page)')
            /*
             * A component is not a handler. The backend's scans read `function NAME(` and attribute every
             * api() inside to NAME, so `export default function VideoShotsPage()` would be charged with every
             * request its inner handlers make (a free sequence plan read as an ungated paid button). A
             * module-level, capitalised function is a component: it is written unnamed here, and the scans
             * see the real handlers, each with its own body.
             */
            .replace(/^(?:export default )?function ([A-Z][\w$]*)\s*\(/gm, 'const $1 = function (');
        if (/<\/template>/i.test(text)) throw new Error(`src/pages/${id}: its source contains </template>, which would end the source block early`);
        return `<template data-react-source="${id}">\n${text}</template>`;
    }).join('\n');
    const css = (f) => read(f).replace(/^\/\* GENERATED by tools\/split-map\.js[^\n]*\*\/\n/, '');
    const out = `<!DOCTYPE html>
<!-- GENERATED by tools/assemble-page.js for the backend's UI tests. Not the app: never served. -->
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Film Engine</title>
    <style>${css('src/styles/base.css')}</style>
<style id="fe-redesign">${css('src/styles/redesign.css')}</style>
</head>
<body>
${body}
${reactSource}
    <script>${read('public/legacy/vendor/three.min.js').replace(/\n$/, '')}</script>
    <script>${read('public/legacy/vendor/gltf-loader.js').replace(/\n$/, '')}</script>
${runs.map(r => `<script data-legacy="${r.file.replace('public/legacy/', '')}">${r.code}\n</script>`).join('\n')}
<script id="production-graph-js">${stripHeader(read('public/legacy/production-graph.js')).replace(/\n$/, '')}</script>
<script id="fe-redesign-js">${stripHeader(read('public/legacy/shell.js')).replace(/\n$/, '')}</script>
</body>
</html>
`;
    fs.writeFileSync(path.join(ROOT, 'src/index.html'), out);
    return { runs: runs.length, bytes: out.length };
}

/*
 * A React page to static HTML, with esbuild (Vite's own) and react-dom/server: no browser, no fetch.
 * Its first render is the page as it stands before its loader runs. Layout effects do not run on the
 * server; React's warning that says so is the one console line silenced here.
 */
function renderReactPage(id) {
    const esbuild = require('esbuild');
    const r = esbuild.buildSync({
        stdin: {
            contents: `import Page from './src/pages/${id}/index.jsx';\nimport { createElement } from 'react';\nimport { renderToStaticMarkup } from 'react-dom/server';\nmodule.exports = renderToStaticMarkup(createElement(Page));\n`,
            resolveDir: ROOT, loader: 'jsx',
        },
        bundle: true, platform: 'node', format: 'cjs', write: false, jsx: 'automatic', logLevel: 'error',
        loader: { '.html': 'text' }, define: { 'process.env.NODE_ENV': '"production"' },
    });
    const mod = { exports: {} };
    const quiet = console.error;
    console.error = (...a) => { if (!/useLayoutEffect does nothing on the server/.test(String(a[0]))) quiet(...a); };
    try { new Function('module', 'exports', 'require', r.outputFiles[0].text)(mod, mod.exports, require); }
    finally { console.error = quiet; }
    if (!new RegExp(`id="page-${id}"`).test(mod.exports)) throw new Error(`React page ${id} did not render id="page-${id}"`);
    return '        ' + mod.exports;
}

module.exports = { assemble };
if (require.main === module) { const r = assemble(); console.log(`src/index.html: ${r.runs} code runs, ${(r.bytes / 1024).toFixed(0)} KB (test-only)`); }
