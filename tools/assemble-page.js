#!/usr/bin/env node
/*
 * Builds src/index.html: a TEST-ONLY reassembly of this app as one page, so the
 * backend's UI tests (which read src/index.html, as they do in film-engine) run
 * against the port's own files. Never served; gitignored; rebuilt by npm test.
 *
 * Everything comes from what this app ships: the markup files, the two
 * stylesheets, and the code in public/legacy (core, chunks, production-graph,
 * shell, vendor). Code is laid out in the source's statement order, one
 * <script data-legacy="…"> per run of statements from the same file, so a test
 * that compiles each script alone sees which file broke, and a test that scans
 * "the next function after X" sees the source's order.
 */
const fs = require('fs');
const path = require('path');
const { parse, readSource, topLevelElements, innerOf } = require('./split-lib');

const ROOT = path.join(__dirname, '..');
const plan = require('./port-plan.json');
const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
const stripHeader = (code) => code.replace(/^\/\* GENERATED by tools\/split-map\.js[^\n]*\*\/\n/, '');

function assemble() {
    const src = readSource(path.join(ROOT, plan.source));
    const map = JSON.parse(read('docs/split-map.json'));

    // ── Code, in source order, from the port's files ────────────────────
    const files = ['public/legacy/core.js', ...Object.keys(map.chunks).map(c => `public/legacy/chunks/${c}.js`)];
    const pool = new Map(); // statement text -> [file, …]
    const navInPort = {};
    for (const f of files) {
        const code = stripHeader(read(f));
        for (const n of parse(code).body) {
            const t = code.slice(n.start, n.end);
            if (n.type === 'FunctionDeclaration' && n.id.name === 'navigateTo') { navInPort.file = f; navInPort.text = t; continue; }
            if (t === `var ${map.core.loaderPlaceholders.join(', ')};`) { navInPort.placeholders = t; continue; } // the port's one added statement
            pool.set(t, [...(pool.get(t) || []), f]);
        }
    }
    const runs = [];
    const appAst = parse(src.app);
    let prev = 0;
    for (const n of appAst.body) {
        const lead = src.app.slice(prev, n.start); // comments and blank lines before it, as in the source
        prev = n.end;
        const t = src.app.slice(n.start, n.end);
        let file, text = t;
        if (n.type === 'FunctionDeclaration' && n.id.name === 'navigateTo') ({ file, text } = { file: navInPort.file, text: (navInPort.placeholders ? navInPort.placeholders + '\n\n    ' : '') + navInPort.text });
        else {
            const at = pool.get(t);
            if (!at || !at.length) throw new Error('a source statement is in no port file: ' + t.slice(0, 80));
            file = at.shift();
        }
        const last = runs[runs.length - 1];
        if (last && last.file === file) last.code += lead + text;
        else runs.push({ file, code: lead + text });
    }
    const left = [...pool.values()].flat();
    if (left.length) throw new Error(`${left.length} port statements matched no source statement`);

    // ── Markup, in the source's body order ──────────────────────────────
    const registry = read('src/pages/registry.js');
    const pageIds = [...registry.matchAll(/\{ id: '([a-z0-9]+)'/g)].map(m => m[1]);
    const modalsIdx = read('src/components/modals/index.js');
    const modals = [...modalsIdx.matchAll(/\{ id: '([^']+)', html: m\d+, inMain: (true|false) \}/g)].map(m => ({ id: m[1], inMain: m[2] === 'true' }));
    const html = (f) => read(f).replace(/\n$/, '');
    const main = '<div class="main">\n' + pageIds.map(id => html(`src/pages/${id}/markup.html`)).join('\n')
        + modals.filter(m => m.inMain).map(m => '\n' + html(`src/components/modals/${m.id}.html`)).join('') + '\n</div>';
    const body = [html('src/components/Sidebar/sidebar.html'), main, html('src/components/StatusBar/status-bar.html'),
        ...modals.filter(m => !m.inMain).map(m => html(`src/components/modals/${m.id}.html`))].join('\n');

    const css = (f) => read(f).replace(/^\/\* GENERATED by tools\/split-map\.js[^\n]*\*\/\n/, '');
    const out = `<!DOCTYPE html>
<!-- GENERATED by tools/assemble-page.js for the backend's UI tests. Not the app: never served. -->
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Film Engine</title>
    <style>${css('src/styles/base.css')}</style>
<style id="fe-redesign">${css('src/styles/redesign.css')}</style>
</head>
<body>
${body}
    <script>${read('public/legacy/vendor/three.min.js').replace(/\n$/, '')}</script>
    <script>${read('public/legacy/vendor/gltf-loader.js').replace(/\n$/, '')}</script>
${runs.map(r => `<script data-legacy="${r.file.replace('public/legacy/', '')}">${r.code}\n</script>`).join('\n')}
<script id="production-graph-js">${stripHeader(read('public/legacy/production-graph.js')).replace(/\n$/, '')}</script>
<script id="fe-redesign-js">${stripHeader(read('public/legacy/shell.js')).replace(/\n$/, '')}</script>
</body>
</html>
`;
    fs.writeFileSync(path.join(ROOT, 'src/index.html'), out);
    return { runs: runs.length, bytes: out.length };
}

module.exports = { assemble };
if (require.main === module) { const r = assemble(); console.log(`src/index.html: ${r.runs} code runs, ${(r.bytes / 1024).toFixed(0)} KB (test-only)`); }
