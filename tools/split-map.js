#!/usr/bin/env node
/*
 * Cuts ../film-engine/src/index.html into this app's files.
 *
 * Markup: every page, the shell and every modal become their own file and are
 * all mounted at boot (other pages read ids out of them). Code: each top-level
 * function of the app script goes to the ONE ported page that alone reaches it
 * (from its loader, its markup, or a modal only it opens), otherwise to core.
 * "Reaches" is any identifier in the text, strings and templates included, so
 * an inline onclick="fn()" counts and anything uncertain stays in core.
 * Page chunks are classic scripts, injected once on first visit, so their
 * functions are globals exactly as in the one-file app.
 *
 *   node tools/split-map.js          write everything
 *   node tools/split-map.js --check  exit 1 if anything is out of date
 */
const fs = require('fs');
const path = require('path');
const { readSource, loaderMap, parse, topLevelElements, innerOf, words, replacedStatement, cutScript, loadTimeCalls, LOAD_TIME_CALLS } = require('./split-lib');

const ROOT = path.join(__dirname, '..');
const plan = require('./port-plan.json');

const HEADER = (what) => `/* GENERATED by tools/split-map.js from film-engine/src/index.html: ${what}. Do not edit; edit the source or the tool. */\n`;

// navigateTo runs a page's loader only once that page's chunk is in.
const LOADERS_RE = /( *)\/\/ Load page data\n([\s\S]*?)PAGE_RELOAD = loaders\[page\] \|\| null;\n\s*if \(loaders\[page\]\) loaders\[page\]\(\);\n([\s\S]*?)setTimeout\(initCollapsibleCards, 60\);\n\s*revealNavGroupFor\(page\);\n\s*writeRoute\(\);\n/;
/*
 * The source runs, in order: PAGE_RELOAD = loader; loader(); setTimeout(initCollapsibleCards, 60);
 * revealNavGroupFor(page); writeRoute(). The port runs exactly that text, unchanged, once the
 * page's chunk is in. While it loads, PAGE_RELOAD is null, so a live refresh cannot rerun the
 * previous page's loader; if another page was chosen meanwhile, this one does nothing.
 * The loaders map names every page's loader; those that live in chunks are declared in core as
 * `var` placeholders (LOADER_PLACEHOLDERS), so the literal evaluates before their chunks load,
 * and each chunk's function declaration fills its own in.
 */
function patchNavigateTo(code) {
    if (!LOADERS_RE.test(code)) throw new Error('navigateTo no longer has the loaders block this tool patches');
    return code.replace(LOADERS_RE, (all, ind) => `${ind}// Load page data — after its script chunk is in (React port: window.__fePages).\n`
        + `${ind}PAGE_RELOAD = null;\n`
        + `${ind}window.__fePages.ensure(page).then(() => {\n`
        + `${ind}if (state.currentPage !== page) return;\n`
        + all
        + `${ind}}).catch(err => { console.error(err); setStatus('Error loading page: ' + err.message); });\n`);
}
const placeholderStatement = (names, ind) => `${ind}// React port: page loaders that live in chunks, declared here so navigateTo's loaders map\n${ind}// evaluates before their chunk loads; each chunk's own function declaration fills its name in.\n${ind}var ${names.join(', ')};\n`;

/*
 * Pages rewritten as React declare it in their own folder (src/pages/<id>/react.json), so two
 * people converting two pages never edit the same file. For each: the loader name navigateTo
 * calls (the React page registers it), the legacy functions it replaces, and the modals it now
 * renders itself.
 */
function readReactPages() {
    const dir = path.join(ROOT, 'src/pages');
    const out = {};
    for (const id of fs.readdirSync(dir)) {
        const f = path.join(dir, id, 'react.json');
        if (!fs.existsSync(f)) continue;
        const j = JSON.parse(fs.readFileSync(f, 'utf8'));
        for (const k of ['loader', 'replaces', 'modals']) if (j[k] === undefined) throw new Error(`src/pages/${id}/react.json: no "${k}"`);
        if (!j.replaces.includes(j.loader)) throw new Error(`src/pages/${id}/react.json: the loader ${j.loader} must be among what it replaces`);
        for (const fn of j.provides || []) if (!j.replaces.includes(fn)) throw new Error(`src/pages/${id}/react.json: ${fn} is provided but not among what it replaces`);
        out[id] = { loader: j.loader, replaces: j.replaces, modals: j.modals, provides: j.provides || [] };
    }
    return out;
}

/*
 * React COMPONENTS that took code over from core declare it the same way, in src/components/<Name>/react.json:
 * what they provide (registered on window when App mounts them, at boot), replace and render. No loader:
 * navigateTo never shows a component. A modal or sheet that every page opens is one.
 */
function readReactComponents() {
    const dir = path.join(ROOT, 'src/components');
    const out = {};
    for (const name of fs.readdirSync(dir).sort()) {
        const f = path.join(dir, name, 'react.json');
        if (!fs.existsSync(f)) continue;
        const j = JSON.parse(fs.readFileSync(f, 'utf8'));
        if ('loader' in j) throw new Error(`src/components/${name}/react.json: a component has no loader (navigateTo never shows it)`);
        for (const k of ['provides', 'replaces', 'modals']) if (!Array.isArray(j[k])) throw new Error(`src/components/${name}/react.json: no "${k}" list`);
        for (const fn of j.provides) if (!j.replaces.includes(fn)) throw new Error(`src/components/${name}/react.json: ${fn} is provided but not among what it replaces`);
        if (!fs.existsSync(path.join(dir, name, name + '.jsx'))) throw new Error(`src/components/${name}: no ${name}.jsx to mount`);
        out[name] = { provides: j.provides, replaces: j.replaces, modals: j.modals };
    }
    return out;
}

/** Every owner of legacy code, keyed `page:<id>` / `component:<Name>`; a name or modal may have only one. */
function ownersOf(react, components) {
    const owners = { ...Object.fromEntries(Object.entries(react).map(([id, r]) => [`page:${id}`, { ...r, registers: [r.loader, ...r.provides] }])),
        ...Object.fromEntries(Object.entries(components).map(([n, r]) => [`component:${n}`, { ...r, registers: r.provides }])) };
    const seen = new Map();
    for (const [o, r] of Object.entries(owners)) {
        for (const key of [...new Set(r.replaces)].map(n => 'name ' + n).concat([...new Set(r.modals)].map(m => 'modal ' + m))) {
            if (seen.has(key)) throw new Error(`${key} has two owners: ${seen.get(key)} and ${o}`);
            seen.set(key, o);
        }
    }
    return owners;
}

/** A script with its comments blanked (same length): what it RUNS, for name checks. */
function codeOnly(code) {
    const comments = [];
    parse(code, comments);
    let out = code;
    for (const c of comments) out = out.slice(0, c.start) + ' '.repeat(c.end - c.start) + out.slice(c.end);
    return out;
}

// The legacy globals React may use (src/lib/legacy.js LEGACY_GLOBALS): core roots, never moved to a chunk.
function readLegacyGlobals() {
    const t = fs.readFileSync(path.join(ROOT, 'src/lib/legacy.js'), 'utf8');
    const m = /LEGACY_GLOBALS\s*=\s*\[([\s\S]*?)\];/.exec(t);
    if (!m) throw new Error('src/lib/legacy.js: no LEGACY_GLOBALS');
    return [...m[1].matchAll(/'([\w$]+)'/g)].map(x => x[1]);
}

function generate({ write = true } = {}) {
    const src = readSource(path.join(ROOT, plan.source));
    const react = readReactPages();
    const components = readReactComponents();
    const owners = ownersOf(react, components);
    const replaced = new Map(Object.entries(owners).flatMap(([o, r]) => r.replaces.map(n => [n, o.replace(/^page:/, '')])));
    const reactModals = new Set(Object.values(owners).flatMap(r => r.modals));
    const registered = new Set(Object.values(owners).flatMap(r => r.registers));
    // The other two boot scripts are emitted whole, less what React replaced from them.
    const cutFrom = {};
    for (const k of ['productionGraph', 'shell']) { const c = cutScript(src[k], new Set(replaced.keys())); src[k] = c.code; cutFrom[k] = c.declared; }
    const legacyGlobals = readLegacyGlobals();
    const ported = new Set(plan.rounds.slice(0, plan.currentRound).flat().filter(p => !react[p]));
    const loaders = loaderMap(src.app);
    const files = {};
    const out = (f, text) => { files[f] = text; };

    // ── Markup ──────────────────────────────────────────────────────────
    const top = topLevelElements(src.html);
    const main = top.find(e => e.cls === 'main');
    const mainInner = innerOf(main.outer);
    const mainKids = topLevelElements(mainInner);
    // Each element keeps the comments that sat just before it in the source (React ignores them;
    // the test-only reassembled page, and anyone reading the file, gets the source's signposts).
    const withLead = (list, html) => list.forEach((e, i) => {
        const lead = html.slice(i ? list[i - 1].end : 0, e.start).replace(/^\s*\n/, '');
        e.outer = (/<!--/.test(lead) ? lead.replace(/\s+$/, '') + '\n' + ' '.repeat((lead.match(/\n( *)$/) || [, ''])[1].length) : '') + e.outer;
    });
    withLead(mainKids, mainInner);
    withLead(top, src.html);
    const pages = mainKids.filter(e => (e.id || '').startsWith('page-')).map(e => ({ id: e.id.slice(5), outer: e.outer }));
    const mainExtras = mainKids.filter(e => !(e.id || '').startsWith('page-'));
    const allModals = [...top.filter(e => /\bmodal-overlay\b/.test(e.cls)), ...mainExtras.filter(e => /\bmodal-overlay\b/.test(e.cls))];
    for (const id of reactModals) if (!allModals.some(m => m.id === id)) throw new Error(`a react.json names modal ${id}, which the source does not have`);
    const modals = allModals.filter(m => !reactModals.has(m.id)); // React pages render their own
    const sidebar = top.find(e => e.tag === 'nav' && /\bsidebar\b/.test(e.cls));
    const statusBar = top.find(e => e.id === 'statusBar');
    const accounted = new Set([main, sidebar, statusBar, ...allModals]);
    // A modal inside .main is placed either way: by ModalHost (legacy) or by the React page or component that owns it.
    const strays = [...top.filter(e => !accounted.has(e)), ...mainExtras.filter(e => !allModals.includes(e))];
    if (strays.length) throw new Error('markup this tool does not place: ' + strays.map(e => e.tag + '#' + e.id).join(', '));
    if (pages.length !== Object.keys(loaders).length) throw new Error('pages and loaders disagree');

    for (const id of Object.keys(react)) if (!pages.some(p => p.id === id)) throw new Error(`src/pages/${id}/react.json: the source has no page ${id}`);
    for (const p of pages) {
        if (react[p.id]) continue; // hand-written React; its index.jsx is not generated
        const comp = componentName(p.id);
        out(`src/pages/${p.id}/markup.html`, p.outer + '\n');
        out(`src/pages/${p.id}/index.jsx`,
            `// GENERATED by tools/split-map.js. The ${p.id} page: its markup, mounted once at boot.\n`
            + `import { memo } from 'react';\nimport LegacyElement from '../../components/LegacyElement.jsx';\nimport html from './markup.html?raw';\n\n`
            + `export default memo(function ${comp}() {\n    return <LegacyElement html={html} />;\n});\n`);
    }
    out('src/components/Sidebar/sidebar.html', sidebar.outer + '\n');
    out('src/components/StatusBar/status-bar.html', statusBar.outer + '\n');
    for (const m of modals) out(`src/components/modals/${m.id}.html`, m.outer + '\n');
    out('src/components/modals/index.js', HEADER('the modal overlays').replace('/*', '//').replace(' */', '')
        + modals.map((m, i) => `import m${i} from './${m.id}.html?raw';`).join('\n')
        + `\n\n// In source order. inMain: the overlay sat inside .main in the source, and still does.\nexport const MODALS = [\n${modals.map((m, i) => `    { id: '${m.id}', html: m${i}, inMain: ${mainExtras.includes(m)} },`).join('\n')}\n];\n`);
    src.styles.forEach((s, i) => out(`src/styles/${i === 0 ? 'base' : 'redesign'}.css`, `/* GENERATED by tools/split-map.js from the source's <style${s.attrs}> block. */\n` + s.css.replace(/^\n/, '')));

    // ── Code ────────────────────────────────────────────────────────────
    // A chunk is one page, or a group of pages that share their code (port-plan.json "groups").
    const chunkOf = (page) => Object.entries(plan.groups || {}).find(([, ms]) => ms.includes(page))?.[0] || page;
    const chunks = [...new Set([...ported].map(chunkOf))];
    const comments = [];
    const ast = parse(src.app, comments);
    // Comments never run: blank them (same length, so offsets hold) before looking for names.
    let appCode = src.app;
    for (const c of comments) appCode = appCode.slice(0, c.start) + ' '.repeat(c.end - c.start) + appCode.slice(c.end);
    let segs = [];
    let prev = 0;
    for (const s of ast.body) { segs.push({ node: s, text: src.app.slice(prev, s.end), code: appCode.slice(prev, s.end) }); prev = s.end; }
    const tail = src.app.slice(prev);
    // What a React page replaces leaves the legacy code entirely: its functions, and its own
    // constants (a const/let/var whose names are all replaced, and whose initialiser runs nothing).
    const declared = new Set(segs.flatMap(s => s.node.type === 'FunctionDeclaration' ? [s.node.id.name]
        : s.node.type === 'VariableDeclaration' ? s.node.declarations.filter(d => d.id.type === 'Identifier').map(d => d.id.name) : []));
    for (const [n, id] of replaced) if (!declared.has(n) && !cutFrom.productionGraph.has(n) && !cutFrom.shell.has(n)) throw new Error(`${id.startsWith('component:') ? 'src/components/' + id.slice(10) : 'src/pages/' + id}/react.json replaces ${n}, which is not a top-level function or variable of any source script`);
    const droppedVars = segs.filter(s => s.node.type === 'VariableDeclaration' && replacedStatement(s.node, replaced));
    for (const s of segs) if (s.node.type === 'VariableDeclaration' && !replacedStatement(s.node, replaced)) {
        const part = s.node.declarations.filter(d => d.id.type === 'Identifier' && replaced.has(d.id.name)).map(d => d.id.name);
        if (part.length) throw new Error(`react.json replaces ${part.join(', ')} but not every name its declaration declares`);
    }
    segs = segs.filter(s => !replacedStatement(s.node, replaced));
    /*
     * Graph nodes: every top-level function declaration, class, and const/let/var
     * whose initialisers run nothing at load (functions, literals, empty
     * new Map()...). A node moves to the one chunk that alone reaches it. Any
     * other statement stays in core, in order, and its names are core roots.
     */
    const isPure = (n) => {
        if (!n) return true;
        switch (n.type) {
            case 'ArrowFunctionExpression': case 'FunctionExpression': case 'Literal': case 'ClassExpression': return true;
            case 'TemplateLiteral': return n.expressions.length === 0;
            case 'UnaryExpression': return isPure(n.argument);
            case 'ArrayExpression': return n.elements.every(e => !e || isPure(e));
            case 'ObjectExpression': return n.properties.every(p => p.type === 'Property' && !p.computed && isPure(p.value));
            case 'CallExpression': // Object.freeze({...}) of pure parts
                return n.callee.type === 'MemberExpression' && n.callee.object.name === 'Object' && n.callee.property.name === 'freeze' && n.arguments.every(isPure);
            case 'Identifier': return n.name === 'undefined' || n.name === 'Infinity' || n.name === 'NaN';
            case 'NewExpression': return n.callee.type === 'Identifier' && ['Map', 'Set', 'WeakMap', 'WeakSet'].includes(n.callee.name) && n.arguments.length === 0;
            default: return false;
        }
    };
    for (const s of droppedVars) if (!s.node.declarations.every(d => isPure(d.init))) {
        throw new Error(`react.json replaces ${s.node.declarations.map(d => d.id.name).join(', ')}, whose initialiser runs code at load: dropping it would drop that too`);
    }
    const declNames = (node) => {
        if (node.type === 'FunctionDeclaration' || node.type === 'ClassDeclaration') return [node.id.name];
        if (node.type === 'VariableDeclaration' && node.declarations.every(d => d.id.type === 'Identifier' && isPure(d.init))) return node.declarations.map(d => d.id.name);
        return null;
    };
    const nameCount = new Map();
    for (const s of segs) for (const n of (s.node.type === 'VariableDeclaration' ? s.node.declarations.flatMap(d => d.id.type === 'Identifier' ? [d.id.name] : []) : s.node.id ? [s.node.id.name] : [])) nameCount.set(n, (nameCount.get(n) || 0) + 1);
    const declCount = new Map([...nameCount].filter(([n]) => segs.some(s => s.node.type === 'FunctionDeclaration' && s.node.id.name === n)));
    const nodeOfName = new Map();   // name -> node id
    const nodeSeg = new Map();      // node id -> segment
    for (const s of segs) {
        if (s.node.type === 'FunctionDeclaration' && s.node.id.name === 'navigateTo') {
            s.text = patchNavigateTo(s.text);
            s.code = s.code.replace(/const loaders = \{[\s\S]*?\n\s*\};/, ''); // the dispatch to every page is not a use of them
        }
        const names = declNames(s.node);
        if (!names || names.some(n => nameCount.get(n) > 1)) continue; // a name declared twice keeps its order in core
        const id = s.node.type === 'FunctionDeclaration' ? names[0] : `${s.node.type === 'ClassDeclaration' ? 'class' : 'var'}:${names.join(',')}`;
        nodeSeg.set(id, s);
        for (const n of names) nodeOfName.set(n, id);
    }
    const fnSeg = new Map([...nodeSeg].filter(([, s]) => s.node.type === 'FunctionDeclaration'));
    const nodeOfSeg = new Map([...nodeSeg].map(([id, s]) => [s, id]));
    /*
     * Statements that only publish or wire functions travel with them:
     * `window.f = f;`, a callback `window.f = function…` (the iOS app's
     * hand-backs), `Object.assign(window, { f, g })`, and a window/document
     * addEventListener. In core they would pin page code at boot; in the chunk
     * they run on first visit, when the functions they name first exist.
     */
    const isWiring = (s) => {
        if (s.node.type !== 'ExpressionStatement') return false;
        const t = src.app.slice(s.node.start, s.node.end);
        // A DOMContentLoaded or load listener must register before those events: never moved.
        if (/^(window|document)\.addEventListener\(\s*['"](DOMContentLoaded|load)['"]/.test(t)) return false;
        return /^window\.[\w$]+\s*=\s*[\w$]+;?$/.test(t) || /^window\.[\w$]+\s*=\s*(?:async\s+)?(?:function\b|\([^)]*\)\s*=>|[\w$]+\s*=>)/.test(t) || /^Object\.assign\(window,\s*\{[\s\w$,]*\}\);?$/.test(t) || /^(window|document)\.addEventListener\(/.test(t);
    };
    const wiring = segs.filter(isWiring);
    const stripHtmlComments = (h) => h.replace(/<!--[\s\S]*?-->/g, '');
    /*
     * Names a text USES. A lookup that cannot throw is not a use: `typeof f`,
     * and `window.f` where the text guards it (`if (window.f)`, `window.f &&`,
     * `window.f?.(`); those run fine before the chunk is in, as they did when
     * the function was simply missing.
     */
    const uses = (code) => {
        const guarded = new Set([...code.matchAll(/(?:if\s*\(\s*!?\s*window\.([\w$]+)\s*[)&|]|window\.([\w$]+)\s*(?:&&|\?)|typeof\s+window\.([\w$]+))/g)].map(m => m[1] || m[2] || m[3]));
        let c = code.replace(/typeof\s+(?:window\.)?[\w$]+/g, ' ');
        if (guarded.size) c = c.replace(/window\.([\w$]+)/g, (all, n) => guarded.has(n) ? ' ' : all);
        return words(c);
    };
    const modalById = new Map(modals.map(m => [m.id, m]));
    const nodeWords = new Map();
    for (const [id, s] of nodeSeg) nodeWords.set(id, uses(s.code));
    for (const m of modals) nodeWords.set('modal:' + m.id, uses(stripHtmlComments(m.outer)));
    const edgesOf = (ws) => { const e = []; for (const w of ws) { const n = nodeOfName.get(w); if (n) e.push(n); if (modalById.has(w)) e.push('modal:' + w); } return e; };

    const fixedCore = [...segs.filter(s => !nodeOfSeg.has(s) && !isWiring(s)).map(s => s.code), tail,
        src.productionGraph, src.shell, stripHtmlComments(sidebar.outer), stripHtmlComments(statusBar.outer),
        ...pages.filter(p => !ported.has(p.id) && !react[p.id]).map(p => stripHtmlComments(p.outer))].join('\n');
    // What the React pages use of the legacy app is core, at boot.
    const fixedCoreWords = new Set([...uses(fixedCore), ...legacyGlobals]);
    // A name on LEGACY_GLOBALS is defined by core, or registered on window by a React page (its loader, what it
    // provides) or component (what it provides): legacy.X reads window, which is where usePageLoader puts those.
    const reactRegistered = new Set([...Object.values(react).flatMap(r => [r.loader, ...r.provides]),
        ...Object.values(components).flatMap(c => c.provides || [])]);
    for (const n of legacyGlobals) if (!nodeOfName.has(n) && !uses(fixedCore).has(n) && !reactRegistered.has(n)) throw new Error(`LEGACY_GLOBALS names ${n}, which neither the legacy code nor a React page or component defines`);
    /*
     * Nothing left may call what a React page replaced: a leftover onclick="addNote()" or a call
     * from another page would now throw. navigateTo's loaders map is the one allowed mention (its
     * entry calls the name the React page registers), and it is already blanked out of s.code.
     */
    {
        const rest = [...segs.map(s => s.code), tail, codeOnly(src.productionGraph), codeOnly(src.shell), sidebar.outer, statusBar.outer,
            ...pages.filter(p => !react[p.id]).map(p => p.outer), ...modals.map(m => m.outer)].map(stripHtmlComments).join('\n');
        // A React page's LOADER may still be called (core refreshes a page after work it did): the page
        // registers it on window before core runs, and core keeps its placeholder var. It may not be DEFINED.
        // ...and so may what it PROVIDES (react.json `provides`: functions it registers on window for core to call).
        const loaders = registered;
        const defined = (n) => new RegExp(`function\\s+${n}\\s*\\(`).test(rest);
        const still = [...replaced.keys()].filter(n => loaders.has(n) ? defined(n) : words(rest).has(n));
        if (still.length) throw new Error('legacy code still uses what a React page replaced: ' + still.map(n => `${n} (${replaced.get(n)})`).join(', '));
    }
    const chunkRoots = Object.fromEntries(chunks.map(c => [c, new Set()]));
    for (const p of pages) if (ported.has(p.id)) for (const w of [...uses(stripHtmlComments(p.outer)), ...loaders[p.id]]) chunkRoots[chunkOf(p.id)].add(w);

    // Wiring starts undecided; any that cannot go to exactly one chunk becomes core, until nothing changes.
    const wiringOwner = new Map(wiring.map(s => [s, null]));
    let reach;
    const computeReach = () => {
        // Names pinned to core (tools/port-plan.json pinToCore, each with its reason) are core roots.
        const roots = { core: new Set([...fixedCoreWords, ...Object.keys(plan.pinToCore || {})]) };
        for (const c of chunks) roots[c] = new Set(chunkRoots[c]);
        for (const [s, o] of wiringOwner) if (o) for (const w of uses(s.code)) roots[o].add(w);
        reach = new Map();
        for (const [group, ws] of Object.entries(roots)) {
            const stack = edgesOf(ws);
            while (stack.length) {
                const n = stack.pop();
                const g = reach.get(n) || new Set();
                if (g.has(group)) continue;
                g.add(group); reach.set(n, g);
                stack.push(...edgesOf(nodeWords.get(n)));
            }
        }
    };
    // Wiring that names only otherwise-unreached code stays undecided until the end, then goes to core.
    const settle = () => {
        for (let changed = true; changed;) {
            changed = false;
            computeReach();
            for (const [s, o] of wiringOwner) {
                if (o === 'core') continue;
                // What it names that core already has is there at boot: only the rest decides.
                const targets = edgesOf(uses(s.code));
                // (that includes what two chunks share: it lands in core too)
                const rest = targets.filter(f => { const g = reach.get(f); return !g || (g.size === 1 && !g.has('core')); });
                const gs = new Set();
                for (const f of rest) for (const g of reach.get(f) || []) gs.add(g);
                const want = rest.length === 0 ? 'core' : gs.size === 0 ? o : gs.size === 1 ? [...gs][0] : 'core';
                if (want !== o && want === 'core' && process.env.SPLIT_WIRING) console.error('wiring->core', appCode.slice(s.node.start, s.node.start + 50).replace(/\s+/g, ' '), 'rest=' + rest.length, [...gs].join(','), edgesOf(uses(s.code)).filter(f => (reach.get(f) || new Set()).has('core')).slice(0, 4).join(' '));
                if (want !== o) { wiringOwner.set(s, want); changed = true; }
            }
        }
    };
    settle();
    /*
     * Still undecided: wiring whose code nothing else reaches (a listener's own
     * handlers). It goes to the one chunk everything downstream of it belongs
     * to, else to core. Before that chunk loads the listener is simply absent,
     * as is all the state its handlers work on.
     */
    for (const [s, o] of wiringOwner) {
        if (o) continue;
        const seen = new Set(), stack = edgesOf(uses(s.code)), gs = new Set();
        while (stack.length) {
            const n = stack.pop();
            if (seen.has(n)) continue;
            seen.add(n);
            const g = reach.get(n);
            if (!g) stack.push(...edgesOf(nodeWords.get(n)));
            else if (g.size === 1 && !g.has('core')) gs.add([...g][0]);
        }
        wiringOwner.set(s, gs.size === 1 ? [...gs][0] : 'core');
    }
    settle();
    const owner = (n) => { const g = reach.get(n); return g && g.size === 1 && !g.has('core') ? [...g][0] : 'core'; };
    const segOwner = (s) => nodeOfSeg.has(s) ? owner(nodeOfSeg.get(s)) : (wiringOwner.get(s) || 'core');
    const chunkCode = Object.fromEntries(chunks.map(c => [c, []]));
    let core = HEADER('the shared core of the app script, in source order; page-only code is in chunks/*.js');
    const chunkLoaders = [...new Set(Object.values(loaders).flat())].filter(n => (nodeOfName.has(n) && owner(nodeOfName.get(n)) !== 'core') || replaced.has(n));
    for (const s of segs) {
        const o = segOwner(s);
        const name = s.node.type === 'FunctionDeclaration' ? s.node.id.name : null;
        if (name === 'navigateTo' && chunkLoaders.length) core += '\n' + placeholderStatement(chunkLoaders, '    ');
        if (o === 'core') core += s.text; else chunkCode[o].push({ name, text: s.text, code: s.code });
    }
    core += tail;

    // Vendored libraries load with the chunks that use them, or at boot if core does.
    const VENDORS = [{ id: 'three', files: ['vendor/three.min.js', 'vendor/gltf-loader.js'], global: 'THREE' }];
    const coreCodeWords = uses([...segs.filter(s => segOwner(s) === 'core').map(s => s.code), tail, src.productionGraph, src.shell].join('\n'));
    const bootVendors = VENDORS.filter(v => coreCodeWords.has(v.global));
    const chunkDeps = Object.fromEntries(chunks.map(c => [c, VENDORS.filter(v => !bootVendors.includes(v) && chunkCode[c].some(f => uses(f.code).has(v.global))).map(v => v.id)]));

    /*
     * A name React registers exists once App has mounted (synchronously, before any legacy script). A call
     * of one while a legacy script LOADS is allowed only where tools/split-lib.js LOAD_TIME_CALLS names it.
     */
    {
        const scripts = [['core.js', core], ['production-graph.js', src.productionGraph], ['shell.js', src.shell],
            ...chunks.map(c => [`chunks/${c}.js`, chunkCode[c].map(f => f.text).join('')])];
        const early = scripts.flatMap(([f, code]) => loadTimeCalls(code, registered).filter(c => !LOAD_TIME_CALLS[c.name]).map(c => `${c.name}() in ${f}`));
        if (early.length) throw new Error('called while the legacy code loads, and registered by React only at mount: ' + early.join(', ')
            + '. Move the call into a function, or name it in tools/split-lib.js LOAD_TIME_CALLS with why it is safe');
    }
    out('public/legacy/core.js', core + '\n');
    const whole = (k) => [...cutFrom[k]].some(n => replaced.has(n)) ? 'whole, less what React replaced' : 'verbatim';
    out('public/legacy/production-graph.js', HEADER(`<script id="production-graph-js">, ${whole('productionGraph')}`) + src.productionGraph + '\n');
    out('public/legacy/shell.js', HEADER(`<script id="fe-redesign-js">, the shell chrome, ${whole('shell')}`) + src.shell + '\n');
    out('public/legacy/vendor/three.min.js', src.three + '\n');
    out('public/legacy/vendor/gltf-loader.js', src.gltf + '\n');
    for (const c of chunks) {
        const members = pages.filter(p => ported.has(p.id) && chunkOf(p.id) === c).map(p => p.id);
        out(`public/legacy/chunks/${c}.js`, HEADER(`the code only ${members.join(', ')} use${members.length > 1 ? '' : 's'}`) + chunkCode[c].map(f => f.text).join('') + '\n');
    }
    const boot = [...bootVendors.flatMap(v => v.files), 'core.js', 'production-graph.js', 'shell.js'];
    out('index.html', fs.readFileSync(path.join(__dirname, 'index.template.html'), 'utf8')
        .replace('<!-- BOOT SCRIPTS -->', boot.map(f => `<script defer src="./legacy/${f}"></script>`).join('\n    ')));
    out('electron/smoke-pages.cjs', `// GENERATED by tools/split-map.js. The pages the smoke run visits, in source order.\nexports.PAGES = ${JSON.stringify(pages.map(p => p.id))};\nexports.CHUNKED = ${JSON.stringify(pages.filter(p => ported.has(p.id)).map(p => p.id))};\n`
        + `// React pages, and the loader each registers on window (src/pages/<id>/react.json).\nexports.REACT = ${JSON.stringify(Object.fromEntries(Object.entries(react).map(([id, r]) => [id, r.loader])))};\n`);
    const comps = Object.keys(components);
    out('src/components/react-components.js', `// GENERATED by tools/split-map.js. The React components that took code over from core (src/components/<Name>/react.json),\n// each mounted once by App at boot, so what it provides is on window before any legacy script runs.\n`
        + comps.map(n => `import ${n} from './${n}/${n}.jsx';`).join('\n') + `${comps.length ? '\n' : ''}\nexport const REACT_COMPONENTS = [${comps.map(n => `\n    { name: '${n}', Component: ${n} },`).join('')}${comps.length ? '\n' : ''}];\n`);
    out('src/pages/registry.js', `// GENERATED by tools/split-map.js. Every page, in source order. chunk: the script that loads on its first visit;\n// react: a React page (src/pages/<id>/react.json), remounted per open project (src/lib/project-epoch.js).\n`
        + pages.map(p => `import ${componentName(p.id)} from './${p.id}/index.jsx';`).join('\n')
        + `\n\nexport const PAGES = [\n${pages.map(p => `    { id: '${p.id}', Component: ${componentName(p.id)}, chunk: ${ported.has(p.id) ? `'${chunkOf(p.id)}'` : 'null'}${react[p.id] ? ', react: true' : ''} },`).join('\n')}\n];\n`
        + `\n// Each chunk, and the vendored libraries it needs first.\nexport const CHUNKS = {\n${chunks.map(c => `    ${c}: { deps: ${JSON.stringify(chunkDeps[c])} },`).join('\n')}\n};\n`
        + `\nexport const VENDORS = {\n${VENDORS.filter(v => !bootVendors.includes(v)).map(v => `    ${v.id}: ${JSON.stringify(v.files)},`).join('\n')}\n};\n`);

    // ── The map ─────────────────────────────────────────────────────────
    const map = { generatedFrom: plan.source, sourceCommit: plan.sourceCommit, round: plan.currentRound, react, reactComponents: components, chunks: {}, pages: {}, core: {} };
    for (const c of chunks) {
        map.chunks[c] = {
            pages: pages.filter(p => ported.has(p.id) && chunkOf(p.id) === c).map(p => p.id),
            deps: chunkDeps[c],
            functions: chunkCode[c].filter(f => f.name).map(f => f.name),
            otherStatements: chunkCode[c].filter(f => !f.name).length,
            bytes: chunkCode[c].reduce((n, f) => n + f.text.length, 0),
        };
    }
    for (const p of pages) {
        const c = ported.has(p.id) ? chunkOf(p.id) : null;
        map.pages[p.id] = { loader: loaders[p.id], chunk: c, modals: c ? modals.filter(m => (reach.get('modal:' + m.id) || new Set()).has(c)).map(m => m.id) : [] };
    }
    const allFns = [...fnSeg.keys()];
    map.core = {
        loaderPlaceholders: chunkLoaders,
        functions: allFns.filter(n => owner(n) === 'core').length,
        unreached: allFns.filter(n => !reach.get(n)).length,
        sharedByChunks: allFns.filter(n => { const g = reach.get(n); return g && !g.has('core') && g.size > 1; }).length,
        declaredTwice: [...declCount].filter(([, c]) => c > 1).map(([n]) => n),
        bootVendors: bootVendors.map(v => v.id),
        bytes: core.length,
    };
    if (process.env.SPLIT_WHY) {
        const cluster = new Set([...nodeSeg.keys()].filter(n => [...(reach.get(n) || [])].join(',') === process.env.SPLIT_WHY));
        const sources = [...segs.filter(s => segOwner(s) === 'core' && !cluster.has(nodeOfSeg.get(s))).map(s => [(nodeOfSeg.get(s) || s.node.type) + ' ' + appCode.slice(s.node.start, s.node.start + 45).replace(/\s+/g, ' '), s.code]),
            ['production-graph', src.productionGraph], ['shell', src.shell], ['sidebar', sidebar.outer], ...pages.filter(p => !ported.has(p.id)).map(p => ['page:' + p.id, p.outer])];
        for (const [l, t] of sources) { const hit = edgesOf(uses(t)).filter(n => cluster.has(n)); if (hit.length) console.error(l, '->', [...new Set(hit)].slice(0, 6).join(' ')); }
    }
    if (process.env.SPLIT_PATH) {
        // The chain by which core reaches a node: core root -> ... -> node.
        const parent = new Map();
        const rootsFrom = new Map();
        const coreSrc = [...segs.filter(s => !nodeOfSeg.has(s) && (!isWiring(s) || (process.env.SPLIT_PATH_WIRING && wiringOwner.get(s) === 'core' && !(process.env.SPLIT_PATH_SKIP && appCode.slice(s.node.start, s.node.end).includes(process.env.SPLIT_PATH_SKIP))))).map(s => [s.node.type + '@' + appCode.slice(s.node.start, s.node.start + 40).replace(/\s+/g, ' '), s.code]),
            ['production-graph', src.productionGraph], ['shell', src.shell], ['sidebar', sidebar.outer], ['statusBar', statusBar.outer], ...pages.filter(p => !ported.has(p.id)).map(p => ['page:' + p.id, p.outer])];
        const q = [];
        for (const [l, t] of coreSrc) for (const n of edgesOf(uses(t))) if (!parent.has(n)) { parent.set(n, null); rootsFrom.set(n, l); q.push(n); }
        while (q.length) { const n = q.shift(); for (const m of edgesOf(nodeWords.get(n) || [])) if (!parent.has(m)) { parent.set(m, n); q.push(m); } }
        for (const target of process.env.SPLIT_PATH.split(',')) {
            const chain = [];
            for (let n = target; n !== null && n !== undefined; n = parent.get(n)) chain.unshift(n);
            console.error(parent.has(target) ? `${rootsFrom.get(chain[0])} => ${chain.join(' -> ')}` : `${target}: not reached from core`);
        }
    }
    if (process.env.SPLIT_DEBUG) {
        const rows = [...nodeSeg].filter(([n]) => owner(n) === 'core').map(([n, s]) => [n, s.text.length, [...(reach.get(n) || [])].join(',')]);
        const byGroup = {};
        for (const [, len, g] of rows) byGroup[g || '(unreached)'] = (byGroup[g || '(unreached)'] || 0) + len;
        console.error(Object.entries(byGroup).sort((a, b) => b[1] - a[1]).slice(0, 20).map(([g, l]) => `${(l / 1024).toFixed(0).padStart(6)} KB  ${g}`).join('\n'));
    }
    out('docs/split-map.json', JSON.stringify(map, null, 2) + '\n');

    if (write) {
        // Generated directories are rewritten whole, so a chunk that no longer exists does not linger.
        for (const d of ['public/legacy/chunks', 'public/legacy/pages']) fs.rmSync(path.join(ROOT, d), { recursive: true, force: true });
    }
    if (write) for (const [f, text] of Object.entries(files)) {
        fs.mkdirSync(path.dirname(path.join(ROOT, f)), { recursive: true });
        fs.writeFileSync(path.join(ROOT, f), text);
    }
    return files;
}

function componentName(id) { return id[0].toUpperCase() + id.slice(1) + 'Page'; }

module.exports = { generate };

if (require.main === module) {
    if (process.argv.includes('--check')) {
        const stale = Object.entries(generate({ write: false })).filter(([f, t]) => !fs.existsSync(path.join(ROOT, f)) || fs.readFileSync(path.join(ROOT, f), 'utf8') !== t);
        if (stale.length) { console.error('out of date:\n' + stale.map(([f]) => '  ' + f).join('\n')); process.exit(1); }
        console.log('split is up to date');
    } else {
        const files = generate();
        const map = JSON.parse(files['docs/split-map.json']);
        console.log(`wrote ${Object.keys(files).length} files; core ${(map.core.bytes / 1024).toFixed(0)} KB, ${map.core.functions} functions`);
        console.log(`boot vendors: ${map.core.bootVendors.join(', ') || 'none'}`);
        for (const [id, c] of Object.entries(map.chunks)) console.log(`  ${id.padEnd(16)} ${String(c.functions.length).padStart(4)} fns ${(c.bytes / 1024).toFixed(0).padStart(5)} KB  deps: ${c.deps.join(',') || '-'}  pages: ${c.pages.join(', ')}`);
    }
}
