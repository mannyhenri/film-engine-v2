#!/usr/bin/env node
/*
 * Cuts ../film-engine/src/index.html into this app's files.
 *
 * Markup: every page, the shell and every modal become their own file and are
 * all mounted at boot (other pages read ids out of them). Code: each top-level
 * function of the app script goes to the ONE ported page that alone reaches it
 * (from its loader, its markup, or a modal only it opens), otherwise to core.
 * "Reaches" is any identifier in the text, strings and templates included, so
 * an inline onclick="fn()" counts and anything uncertain stays in core.
 * Page chunks are classic scripts, injected once on first visit, so their
 * functions are globals exactly as in the one-file app.
 *
 *   node tools/split-map.js          write everything
 *   node tools/split-map.js --check  exit 1 if anything is out of date
 */
const fs = require('fs');
const path = require('path');
const { readSource, loaderMap, parse, topLevelElements, innerOf, words } = require('./split-lib');

const ROOT = path.join(__dirname, '..');
const plan = require('./port-plan.json');

const HEADER = (what) => `/* GENERATED by tools/split-map.js from film-engine/src/index.html: ${what}. Do not edit; edit the source or the tool. */\n`;

// navigateTo runs a page's loader only once that page's chunk is in.
const LOADERS_RE = /( *)\/\/ Load page data\n([\s\S]*?)PAGE_RELOAD = loaders\[page\] \|\| null;\n\s*if \(loaders\[page\]\) loaders\[page\]\(\);\n([\s\S]*?)setTimeout\(initCollapsibleCards, 60\);\n/;
function patchNavigateTo(code) {
    if (!LOADERS_RE.test(code)) throw new Error('navigateTo no longer has the loaders block this tool patches');
    return code.replace(LOADERS_RE, (all, ind, map, between) => {
        // Each loader is looked up when it runs: a page's function does not exist until its chunk is in.
        const lazy = map.replace(/^(\s*)([A-Za-z_$][\w$]*): ([A-Za-z_$][\w$]*),$/gm, '$1$2: () => $3(),');
        return `${ind}// Load page data — after its script chunk is in (React port: window.__fePages).\n`
            + `${ind}const __fePage = page;\n`
            + `${ind}window.__fePages.ensure(page).then(() => {\n`
            + `${ind}if (state.currentPage !== __fePage) return;\n`
            + lazy
            + `${ind}PAGE_RELOAD = loaders[page] || null;\n${ind}if (loaders[page]) loaders[page]();\n`
            + between
            + `${ind}setTimeout(initCollapsibleCards, 60);\n${ind}}).catch(err => { console.error(err); setStatus('Error loading page: ' + err.message); });\n`;
    });
}

function generate({ write = true } = {}) {
    const src = readSource(path.join(ROOT, plan.source));
    const ported = new Set(plan.rounds.slice(0, plan.currentRound).flat());
    const loaders = loaderMap(src.app);
    const files = {};
    const out = (f, text) => { files[f] = text; };

    // ── Markup ──────────────────────────────────────────────────────────
    const top = topLevelElements(src.html);
    const main = top.find(e => e.cls === 'main');
    const mainKids = topLevelElements(innerOf(main.outer));
    const pages = mainKids.filter(e => (e.id || '').startsWith('page-')).map(e => ({ id: e.id.slice(5), outer: e.outer }));
    const mainExtras = mainKids.filter(e => !(e.id || '').startsWith('page-'));
    const modals = [...top.filter(e => /\bmodal-overlay\b/.test(e.cls)), ...mainExtras.filter(e => /\bmodal-overlay\b/.test(e.cls))];
    const sidebar = top.find(e => e.tag === 'nav' && /\bsidebar\b/.test(e.cls));
    const statusBar = top.find(e => e.id === 'statusBar');
    const accounted = new Set([main, sidebar, statusBar, ...modals]);
    const strays = [...top.filter(e => !accounted.has(e)), ...mainExtras.filter(e => !modals.includes(e))];
    if (strays.length) throw new Error('markup this tool does not place: ' + strays.map(e => e.tag + '#' + e.id).join(', '));
    if (pages.length !== Object.keys(loaders).length) throw new Error('pages and loaders disagree');

    for (const p of pages) {
        const comp = componentName(p.id);
        out(`src/pages/${p.id}/markup.html`, p.outer + '\n');
        out(`src/pages/${p.id}/index.jsx`,
            `// GENERATED by tools/split-map.js. The ${p.id} page: its markup, mounted once at boot.\n`
            + `import { memo } from 'react';\nimport LegacyElement from '../../components/LegacyElement.jsx';\nimport html from './markup.html?raw';\n\n`
            + `export default memo(function ${comp}() {\n    return <LegacyElement html={html} />;\n});\n`);
    }
    out('src/components/Sidebar/sidebar.html', sidebar.outer + '\n');
    out('src/components/StatusBar/status-bar.html', statusBar.outer + '\n');
    for (const m of modals) out(`src/components/modals/${m.id}.html`, m.outer + '\n');
    out('src/components/modals/index.js', HEADER('the modal overlays').replace('/*', '//').replace(' */', '')
        + modals.map((m, i) => `import m${i} from './${m.id}.html?raw';`).join('\n')
        + `\n\n// In source order. inMain: the overlay sat inside .main in the source, and still does.\nexport const MODALS = [\n${modals.map((m, i) => `    { id: '${m.id}', html: m${i}, inMain: ${mainExtras.includes(m)} },`).join('\n')}\n];\n`);
    out('electron/smoke-pages.cjs', `// GENERATED by tools/split-map.js. The pages the smoke run visits, in source order.\nexports.PAGES = ${JSON.stringify(pages.map(p => p.id))};\nexports.CHUNKED = ${JSON.stringify(pages.filter(p => ported.has(p.id)).map(p => p.id))};\n`);
    out('src/pages/registry.js', `// GENERATED by tools/split-map.js. Every page, in source order. chunk: its code loads on first visit.\n`
        + pages.map(p => `import ${componentName(p.id)} from './${p.id}/index.jsx';`).join('\n')
        + `\n\nexport const PAGES = [\n${pages.map(p => `    { id: '${p.id}', Component: ${componentName(p.id)}, chunk: ${ported.has(p.id)} },`).join('\n')}\n];\n`);
    src.styles.forEach((s, i) => out(`src/styles/${i === 0 ? 'base' : 'redesign'}.css`, `/* GENERATED by tools/split-map.js from the source's <style${s.attrs}> block. */\n` + s.css.replace(/^\n/, '')));

    // ── Code ────────────────────────────────────────────────────────────
    const ast = parse(src.app);
    const segs = [];
    let prev = 0;
    for (const s of ast.body) { segs.push({ node: s, text: src.app.slice(prev, s.end) }); prev = s.end; }
    const tail = src.app.slice(prev);
    const fnSeg = new Map();
    const declCount = new Map();
    for (const s of segs) if (s.node.type === 'FunctionDeclaration') declCount.set(s.node.id.name, (declCount.get(s.node.id.name) || 0) + 1);
    for (const s of segs) {
        if (s.node.type !== 'FunctionDeclaration') continue;
        const name = s.node.id.name;
        if (name === 'navigateTo') s.text = patchNavigateTo(s.text);
        if (declCount.get(name) === 1) fnSeg.set(name, s); // a name declared twice keeps its override order in core
    }
    const modalById = new Map(modals.map(m => [m.id, m]));
    // Graph: functions and modals, edges by identifiers in their text.
    const nodeWords = new Map();
    for (const [name, s] of fnSeg) {
        // navigateTo's loader map is the dispatch to every page, not a use of them.
        nodeWords.set(name, words(name === 'navigateTo' ? s.text.replace(/const loaders = \{[\s\S]*?\n\s*\};/, '') : s.text));
    }
    for (const m of modals) nodeWords.set('modal:' + m.id, words(m.outer));
    const edgesOf = (ws) => { const e = []; for (const w of ws) { if (fnSeg.has(w)) e.push(w); if (modalById.has(w)) e.push('modal:' + w); } return e; };

    const coreText = [...segs.filter(s => s.node.type !== 'FunctionDeclaration' || !fnSeg.has(s.node.id.name)).map(s => s.text), tail,
        src.productionGraph, src.shell, sidebar.outer, statusBar.outer, ...pages.filter(p => !ported.has(p.id)).map(p => p.outer)].join('\n');
    const roots = { core: edgesOf(words(coreText)) };
    for (const p of pages) if (ported.has(p.id)) roots[p.id] = edgesOf(new Set([...words(p.outer), ...loaders[p.id]]));
    const reach = new Map();
    for (const [group, start] of Object.entries(roots)) {
        const stack = [...start];
        while (stack.length) {
            const n = stack.pop();
            const g = reach.get(n) || new Set();
            if (g.has(group)) continue;
            g.add(group); reach.set(n, g);
            stack.push(...edgesOf(nodeWords.get(n)));
        }
    }
    const owner = (n) => { const g = reach.get(n); return g && g.size === 1 && !g.has('core') ? [...g][0] : 'core'; };

    const pageCode = Object.fromEntries([...ported].map(id => [id, []]));
    let core = HEADER('the shared core of the app script, in source order; page-only functions are in pages/*.js');
    for (const s of segs) {
        const name = s.node.type === 'FunctionDeclaration' && fnSeg.has(s.node.id.name) ? s.node.id.name : null;
        const o = name ? owner(name) : 'core';
        if (o === 'core') core += s.text; else pageCode[o].push({ name, text: s.text });
    }
    core += tail;
    out('public/legacy/core.js', core + '\n');
    out('public/legacy/production-graph.js', HEADER('<script id="production-graph-js">, verbatim') + src.productionGraph + '\n');
    out('public/legacy/shell.js', HEADER('<script id="fe-redesign-js">, the shell chrome, verbatim') + src.shell + '\n');
    out('public/legacy/vendor/three.min.js', src.three + '\n');
    out('public/legacy/vendor/gltf-loader.js', src.gltf + '\n');
    for (const [id, fns] of Object.entries(pageCode)) {
        out(`public/legacy/pages/${id}.js`, HEADER(`the functions only the ${id} page uses`) + fns.map(f => f.text).join('') + '\n');
    }

    // ── The map ─────────────────────────────────────────────────────────
    const map = { generatedFrom: plan.source, round: plan.currentRound, pages: {}, core: {} };
    for (const p of pages) {
        map.pages[p.id] = {
            loader: loaders[p.id],
            chunk: ported.has(p.id),
            functions: ported.has(p.id) ? pageCode[p.id].map(f => f.name) : [],
            modals: modals.filter(m => (reach.get('modal:' + m.id) || new Set()).has(p.id)).map(m => m.id),
            bytes: ported.has(p.id) ? pageCode[p.id].reduce((n, f) => n + f.text.length, 0) : 0,
        };
    }
    const allFns = [...fnSeg.keys()];
    map.core = {
        functions: allFns.filter(n => owner(n) === 'core').length,
        unreached: allFns.filter(n => !reach.get(n)).length,
        sharedByPages: allFns.filter(n => { const g = reach.get(n); return g && !g.has('core') && g.size > 1; }).length,
        declaredTwice: [...declCount].filter(([, c]) => c > 1).map(([n]) => n),
        bytes: core.length,
    };
    out('docs/split-map.json', JSON.stringify(map, null, 2) + '\n');

    if (write) for (const [f, text] of Object.entries(files)) {
        fs.mkdirSync(path.dirname(path.join(ROOT, f)), { recursive: true });
        fs.writeFileSync(path.join(ROOT, f), text);
    }
    return files;
}

function componentName(id) { return id[0].toUpperCase() + id.slice(1) + 'Page'; }

module.exports = { generate };

if (require.main === module) {
    if (process.argv.includes('--check')) {
        const stale = Object.entries(generate({ write: false })).filter(([f, t]) => !fs.existsSync(path.join(ROOT, f)) || fs.readFileSync(path.join(ROOT, f), 'utf8') !== t);
        if (stale.length) { console.error('out of date:\n' + stale.map(([f]) => '  ' + f).join('\n')); process.exit(1); }
        console.log('split is up to date');
    } else {
        const files = generate();
        const map = JSON.parse(files['docs/split-map.json']);
        console.log(`wrote ${Object.keys(files).length} files; core ${(map.core.bytes / 1024).toFixed(0)} KB, ${map.core.functions} functions`);
        for (const [id, p] of Object.entries(map.pages)) if (p.chunk) console.log(`  ${id.padEnd(12)} ${String(p.functions.length).padStart(4)} fns ${(p.bytes / 1024).toFixed(0).padStart(5)} KB  modals: ${p.modals.join(', ') || '-'}`);
    }
}
